#!/usr/bin/env python3
"""Generate the root marketplaces and per-client plugin files from each plugin's spec `plugin.json`.

Source of truth: plugins/<name>/plugin.json (Agent Plugins 1.0), whose only portable components are
skills/ and mcp.json. Codex and Copilot read that package natively. Everything client-specific is
generated here, so it cannot drift:
  .claude-plugin/marketplace.json   (Claude Code; Copilot reads it too)
  .agents/plugins/marketplace.json  (Codex)
  .cursor-plugin/marketplace.json   (Cursor; each entry resolves through the plugin's .cursor-plugin/)
  plugins/<name>/.cursor-plugin/plugin.json  Cursor loads agents, hooks and MCP only from its own
                                    manifest: skills, plus com.cursor/hooks/hooks.json, agents/ and
                                    mcp.json where the plugin has them
  plugins/<name>/.mcp.json          Claude Code reads only this name, never the spec mcp.json
  plugins/<name>/agents/<a>.md and plugins/<name>/com.github.copilot/agents/<a>.agent.md
                                    sub-agents declared in scripts/agents.json, bodies concatenated
                                    from skill reference files (Claude + Cursor read the first,
                                    Copilot only the second; Codex loads no agents from plugins)

Usage:  uv run python scripts/sync_manifests.py [--check]
--check exits 1 if any generated file is out of date (CI / validate.sh).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGINS = ROOT / "plugins"
SPEC_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
OWNER = {"name": "Wade Cooper", "email": "wadetcooper@gmail.com"}
MARKETPLACE_NAME = "ai-security-sdlc"
MARKETPLACE_DESC = "Agent plugins for securing an AI-first SDLC: secure agent setup and starter templates, secure-by-design planning, AI evals, red teaming, pentest, SAST and remediation."
CURSOR_HOOKS = "com.cursor/hooks/hooks.json"
AGENTS = ROOT / "scripts/agents.json"
# Read-only tool sets. Cursor strips `tools`/`model` from plugin agents and honours only
# `permissionMode: readonly`; Claude ignores that key for plugin agents. Copilot CLI names the tools
# view/grep/glob, VS Code documents read/search; unknown names are ignored, so ship the union.
CLAUDE_READONLY = "Read, Glob, Grep"
COPILOT_READONLY = ["view", "grep", "glob", "read", "search"]


def agent_files(pdir: Path, agent: dict) -> list[tuple[Path, str]]:
    body = []
    for src in agent["sources"]:
        text = (pdir / src["path"]).read_text()
        if src.get("cut"):
            text = text.split(src["cut"])[0]
        body.append(text.strip() + "\n")
    note = f"<!-- Generated by scripts/sync_manifests.py from {', '.join(s['path'] for s in agent['sources'])}; edit those files. -->\n\n"
    text = note + "\n".join(body)
    name, desc = agent["name"], json.dumps(agent["description"], ensure_ascii=False)
    claude = f"---\nname: {name}\ndescription: {desc}\ntools: {CLAUDE_READONLY}\nmodel: inherit\npermissionMode: readonly\n---\n\n{text}"
    copilot = f"---\nname: {name}\ndescription: {desc}\ntools: {json.dumps(COPILOT_READONLY)}\n---\n\n{text}"
    return [(pdir / f"agents/{name}.md", claude), (pdir / f"com.github.copilot/agents/{name}.agent.md", copilot)]


def dump(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    stale: list[Path] = []
    entries = []
    outputs: list[tuple[Path, dict | str | None]] = []
    agents = json.loads(AGENTS.read_text())["agents"]
    for pdir in sorted(p for p in PLUGINS.iterdir() if (p / "plugin.json").exists()):
        spec = json.loads((pdir / "plugin.json").read_text())
        assert spec.get("$schema") == SPEC_SCHEMA, f"{pdir}: plugin.json must declare $schema {SPEC_SCHEMA}"
        mine = [a for a in agents if a["plugin"] == pdir.name]
        for a in mine:
            outputs += agent_files(pdir, a)
        cursor = {k: spec[k] for k in ("name", "version", "description", "author", "homepage", "repository", "license", "keywords") if k in spec}
        cursor["skills"] = "./skills/"
        if mine:
            cursor["agents"] = "./agents/"
        if (pdir / CURSOR_HOOKS).exists():   # an explicit path also stops Cursor scanning the Claude-format hooks/
            cursor["hooks"] = f"./{CURSOR_HOOKS}"
        mcp = None
        if (pdir / "mcp.json").exists():     # explicit path, so Cursor does not load the generated .mcp.json twice
            cursor["mcpServers"] = "./mcp.json"
            mcp = {k: v for k, v in json.loads((pdir / "mcp.json").read_text()).items() if k != "$schema"}
        outputs += [(pdir / ".cursor-plugin/plugin.json", cursor), (pdir / ".mcp.json", mcp)]
        entries.append({
            "name": spec["name"],
            "description": spec["description"],
            "version": spec.get("version"),
            "source": f"./plugins/{pdir.name}",
            "category": "security",
            "author": spec.get("author", OWNER),
        })
    claude_mp = {
        "name": MARKETPLACE_NAME,
        "description": MARKETPLACE_DESC,
        "owner": OWNER,
        "plugins": entries,
    }
    cursor_mp = {
        "name": MARKETPLACE_NAME,
        "owner": OWNER,
        "metadata": {"description": MARKETPLACE_DESC},
        "plugins": [{"name": e["name"], "description": e["description"], "version": e["version"], "source": e["source"]} for e in entries],
    }
    codex_mp = {
        "name": MARKETPLACE_NAME,
        "interface": {"displayName": "AI Security SDLC"},
        "plugins": [
            {"name": e["name"], "source": {"source": "local", "path": e["source"]}, "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"}, "category": "Security"}
            for e in entries
        ],
    }
    outputs += [(ROOT / ".claude-plugin/marketplace.json", claude_mp), (ROOT / ".agents/plugins/marketplace.json", codex_mp),
                (ROOT / ".cursor-plugin/marketplace.json", cursor_mp)]
    for out, content in outputs:
        if content is None:  # no longer wanted: remove the generated file and its now-empty directory
            if out.exists():
                stale.append(out)
                if not check:
                    out.unlink()
                    if not any(out.parent.iterdir()):
                        out.parent.rmdir()
            continue
        text = content if isinstance(content, str) else dump(content)
        if not out.exists() or out.read_text() != text:
            stale.append(out)
            if not check:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(text)
    if check and stale:
        print("stale manifests:\n  " + "\n  ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    print(f"{'checked' if check else 'wrote'} {len(entries)} plugins, {len(agents)} agents; {len(stale)} file(s) {'stale' if check else 'updated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
